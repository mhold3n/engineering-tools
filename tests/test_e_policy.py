"""Phase E U7: coupling policy compile + preCICE 3 backend XML.

Agents: C/D XML is generated by c_backend_precice. These tests must not
patch default_policy or tight_d_policy. Displacement Aitken is broken.
"""

from __future__ import annotations

import ast
from pathlib import Path

from engineering_tools.e_backend_precice import generate_e_precice_config
from engineering_tools.e_policy import (
    compile_coupling_policy,
    coupling_session,
    mechanical_thermal_exchanges,
)


def test_mechanical_and_thermal_exchanges_coexist_in_one_config() -> None:
    policy = compile_coupling_policy(
        kind="implicit two-way",
        exchanges=mechanical_thermal_exchanges(),
    )
    assert policy["status"] == "ok"
    xml = generate_e_precice_config(policy)
    assert 'exchange data="Displacement"' in xml
    assert 'exchange data="Force"' in xml
    assert "Traction" not in xml
    assert 'exchange data="Temperature"' in xml
    assert 'exchange data="Heat-Flux"' in xml
    assert xml.count("<exchange ") == 4


def test_compressible_fluid_metadata_does_not_need_run_gas_special() -> None:
    """Same compile + generate functions; gas is region_physics metadata."""
    policy = compile_coupling_policy(
        kind="implicit two-way",
        region_physics=["compressible_fluid", "deformable_solid"],
        exchanges=mechanical_thermal_exchanges(),
    )
    assert policy["status"] == "ok"
    assert "compressible_fluid" in policy["region_physics"]
    xml = generate_e_precice_config(policy)
    assert "Force" in xml
    src_root = Path("src/engineering_tools")
    defined: set[str] = set()
    for path in (src_root / "e_policy.py", src_root / "e_backend_precice.py"):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        defined.update(
            node.name for node in ast.walk(tree) if isinstance(node, ast.FunctionDef)
        )
    assert "compile_coupling_policy" in defined
    assert "generate_e_precice_config" in defined
    assert "run_gas_special" not in defined


def test_one_way_omits_implicit_iteration_markers() -> None:
    one = compile_coupling_policy(
        kind="one-way",
        exchanges=[{"quantity": "displacement", "from": "Solid", "to": "Fluid"}],
    )
    two = compile_coupling_policy(kind="implicit two-way")
    one_xml = generate_e_precice_config(one)
    two_xml = generate_e_precice_config(two)
    for marker in (
        "coupling-scheme:serial-implicit",
        "max-iterations",
        "relative-convergence-measure",
        "acceleration:aitken",
    ):
        assert marker in two_xml
        assert marker not in one_xml
    assert "coupling-scheme:serial-explicit" in one_xml


def test_invalid_policy_backend_combo_fails() -> None:
    unknown_backend = compile_coupling_policy(kind="one-way", backend="homegrown")
    assert unknown_backend["status"] == "broken"
    unknown_kind = compile_coupling_policy(kind="loose-fsi", backend="precice")
    assert unknown_kind["status"] == "broken"
    aitken_on_one_way = compile_coupling_policy(
        kind="one-way",
        aitken_data=["Force"],
        exchanges=[{"quantity": "displacement", "from": "Solid", "to": "Fluid"}],
    )
    assert aitken_on_one_way["status"] == "broken"
    # First→second Displacement Aitken is the C/D illegal case.
    illegal = compile_coupling_policy(
        kind="implicit two-way",
        aitken_data=["Displacement"],
    )
    assert illegal["status"] == "broken"
    assert "Displacement" in str(illegal["detail"])


def test_checkpoint_requirement_in_policy_and_session_when_requested() -> None:
    requested = compile_coupling_policy(
        kind="implicit two-way",
        require_checkpoint=True,
    )
    assert requested["checkpoint_required"] is True
    session = coupling_session(requested)
    assert session["checkpoint_required"] is True
    assert session["status"] == "ok"
    not_requested = compile_coupling_policy(kind="one-way")
    assert not_requested["checkpoint_required"] is False
    assert coupling_session(not_requested)["checkpoint_required"] is False


def test_explicit_and_multirate_kinds_compile() -> None:
    explicit = compile_coupling_policy(kind="explicit two-way")
    multi = compile_coupling_policy(kind="multirate implicit", second_dt=0.001)
    assert explicit["status"] == "ok"
    assert multi["status"] == "ok"
    explicit_xml = generate_e_precice_config(explicit)
    multi_xml = generate_e_precice_config(multi)
    assert "serial-explicit" in explicit_xml
    assert "max-iterations" not in explicit_xml
    assert "serial-implicit" in multi_xml
    assert 'substeps="true"' in multi_xml
    assert 'substeps="true"' not in generate_e_precice_config(
        compile_coupling_policy(kind="implicit two-way")
    )


def test_precice3_shape_and_aitken_only_second_to_first() -> None:
    xml = generate_e_precice_config(compile_coupling_policy(kind="implicit two-way"))
    assert "solver-interface" not in xml
    assert "<solver:" not in xml
    assert '<mesh name="interface" dimensions="3">' in xml
    assert '<mesh name="interface-fluid" dimensions="3">' in xml
    assert 'm2n:sockets acceptor="Fluid" connector="Solid"' in xml
    assert "m2n:sockets from=" not in xml
    aitken_start = xml.index("<acceleration:aitken>")
    aitken_end = xml.index("</acceleration:aitken>")
    aitken = xml[aitken_start:aitken_end]
    assert 'data name="Force"' in aitken
    assert 'data name="Heat-Flux"' in aitken
    assert 'data name="Displacement"' not in aitken
    assert 'data name="Temperature"' not in aitken
